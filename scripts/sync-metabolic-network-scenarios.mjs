#!/usr/bin/env node
/**
 * Publishes the metabolic network scenario data for the Model page
 * (src/contents/Model/MetabolicNetworkGraph.tsx, data layer in
 * src/contents/Model/scenarioData.ts).
 *
 * Input:  data/metabolic-network-scenarios/ — manifest.json (the sidebar's
 *         source of truth for every objective, perturbation, checkpoint,
 *         and predicted-state figure) plus one raw Fluxer export per
 *         scenario (152 of them at the time of writing).
 * Output: public/generated/scenarios/ — the same files, byte-identical,
 *         copied (not merged or transformed) so the browser can fetch
 *         manifest.json once and then any *individual* scenario file on
 *         demand. Not committed; see .gitignore. Regenerated by `yarn dev`
 *         / `yarn build` (see package.json).
 *
 * This replaces the old generate-metabolic-network.mjs, which merged
 * exactly three scenario exports into one build-time union JSON so the
 * frontend never had to fetch more than once. That approach doesn't
 * generalize here: there are 152 scenarios spanning 69–5070 nodes each,
 * selected by a sidebar of independent filters rather than a single
 * 3-position slider, and downloading (let alone merging) all of them up
 * front would badly defeat the point of on-demand loading. So the
 * transform step is gone — the browser now fetches and parses each raw
 * Fluxer export itself, on demand (see scenarioData.ts's `parseScenarioGraph`)
 * — and this script's only job is making the already-final source files
 * reachable over HTTP in dev and in the built site.
 *
 * Incremental: skips a file whose destination already exists with the same
 * byte size, so a first `yarn dev`/`yarn build` copies everything (roughly
 * 150–250 MB across 152 files) but every run after that is close to
 * instant. Run directly for local inspection:
 * `node scripts/sync-metabolic-network-scenarios.mjs`
 */

import { readdir, mkdir, copyFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC_DIR = path.join(ROOT, "data", "metabolic-network-scenarios");
const OUT_DIR = path.join(ROOT, "public", "generated", "scenarios");

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const entries = await readdir(SRC_DIR, { withFileTypes: true });
  const files = entries.filter((e) => e.isFile() && e.name.endsWith(".json")).map((e) => e.name);

  let copied = 0;
  let skipped = 0;
  for (const name of files) {
    const srcPath = path.join(SRC_DIR, name);
    const outPath = path.join(OUT_DIR, name);

    const srcStat = await stat(srcPath);
    const outStat = await stat(outPath).catch(() => null);
    if (outStat && outStat.size === srcStat.size) {
      skipped++;
      continue;
    }

    await copyFile(srcPath, outPath);
    copied++;
  }

  console.log(
    `[sync-metabolic-network-scenarios] ${files.length} files (${copied} copied, ${skipped} already up to date) -> ` +
      path.relative(ROOT, OUT_DIR),
  );
}

main().catch((err) => {
  console.error("[sync-metabolic-network-scenarios] failed:", err);
  process.exitCode = 1;
});
