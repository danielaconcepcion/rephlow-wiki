#!/usr/bin/env node
/**
 * Preprocesses the Fluxer graph export(s) for the Model page's metabolic
 * network visualization (src/contents/Model/MetabolicNetworkGraph.tsx).
 *
 * Input:  data/ijn1463_fluxer_*_subsystems.json — one file per objective-
 *         function scenario (see SCENARIOS below). Each is a Fluxer graph
 *         response for the iJN1463 model, filtered by the team to remove
 *         zero-flux reactions and orphaned nodes, with a real `subsystem`
 *         field on every reaction node. The biomass and 60/40 files also
 *         have cofactors removed upstream; the polyphosphate file does not
 *         (see "Cofactors" below) — this script doesn't filter by
 *         `IsCofactor` itself either way, it only reflects whatever each
 *         source file already contains.
 * Output: public/generated/metabolic-network.json
 *         A minimal Cytoscape.js elements payload with only the fields the
 *         browser needs. Regenerated by `yarn dev` / `yarn build` (see
 *         package.json) — not committed; see .gitignore.
 *
 * Run directly for local inspection: `node scripts/generate-metabolic-network.mjs`
 *
 * --- Coloring: real curated subsystems, not a computed proxy ---
 * An earlier version of this script derived a structural "module" via
 * graph clustering because the source data had no subsystem field. This
 * export does carry one (on reaction nodes only), so that computed proxy
 * is gone entirely — reactions are grouped and colored by their actual
 * `subsystem` value. Metabolites are not assigned a subsystem (a
 * metabolite can be shared by many subsystems, and the source data does
 * not curate one "owning" subsystem for it), so they all render as a
 * single flat color instead — see MetabolicNetworkGraph.tsx.
 *
 * Reaction subsystem strings (e.g. "S_Fatty_Acid__Biosynthesis") are
 * mapped to a stable `subsystemIndex` here — sorted alphabetically, over
 * the union of every scenario's subsystems, so the mapping doesn't depend
 * on input order or on which scenario is active. The human-readable label
 * shown in tooltips is derived from the same string (stripping the "S_"
 * prefix and underscores), not invented.
 *
 * --- Multiple scenarios, one graph ---
 * Each scenario file is its own Fluxer export with its own (mostly, not
 * fully, overlapping) set of nonzero-flux reactions/metabolites and edges.
 * Rather than ship one graph per scenario — which would force the page to
 * tear down and rebuild the whole visualization on every switch — this
 * script builds one UNION graph across every scenario. Every node/edge that
 * appears in *any* scenario is included once; each carries a `scenarios`
 * map of per-scenario `{ flux, active }` (nodes) or `{ flux, fluxNorm,
 * active }` (edges), so a node's identity never changes between scenarios
 * — only which nodes/edges are active (opacity) and how thick the active
 * edges are. Edge width uses one shared log scale computed across every
 * scenario's flux values combined, so a given flux magnitude always maps
 * to the same pixel width regardless of which objective is active. The
 * component seeds each element's top-level `flux`/`fluxNorm`/`active`
 * fields (which its draw loop reads) from `defaultScenario`, then re-reads
 * the `scenarios` map on every switch.
 *
 * To add another scenario later, add one entry to SCENARIOS below with its
 * Fluxer export file and a label — everything else (union graph, shared
 * color/width scales, and the objective slider in
 * MetabolicNetworkGraph.tsx, which renders directly off the generated
 * `scenarios` list) picks it up with no further code changes.
 *
 * --- Cofactors ---
 * Unlike the other two scenario files, ijn1463_fluxer_polyp_subsystems.json
 * still includes cofactor nodes/edges (IsCofactor: true) — the team did not
 * strip them upstream for this export. They're kept as-is here rather than
 * filtered out: at 69 nodes / 110 edges total for this scenario (19 of them
 * cofactors), the file is small enough that neither performance nor
 * readability is a real concern, so there's nothing to justify silently
 * dropping data the team chose to include. If a future, larger
 * polyphosphate-family export makes cofactor clutter an actual problem,
 * that's a decision to make explicitly then, not something to bake in here
 * pre-emptively.
 *
 * --- No precomputed layout ---
 * An earlier version of this script ran a full 'cose' layout here, once,
 * in a headless Cytoscape instance, and baked the resulting x/y into the
 * generated JSON. The component no longer uses Cytoscape or that
 * precomputed layout: it's a plain d3-force simulation, and d3-force
 * already gives every node a deterministic, zero-cost initial position
 * (a golden-angle spiral around the origin) whenever a node has no x/y of
 * its own — see MetabolicNetworkGraph.tsx. Precomputing positions here
 * would just be extra build time and an extra devDependency for a layout
 * the simulation immediately relaxes away from regardless, so this script
 * no longer produces a `position` field at all.
 */

import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DATA_DIR = path.join(ROOT, "data");
const OUTPUT_PATH = path.join(ROOT, "public", "generated", "metabolic-network.json");

const SCENARIOS = [
  { id: "biomass", label: "Biomass maximization", file: "ijn1463_fluxer_biomass_subsystems.json" },
  {
    id: "biomass60_polyp40",
    label: "60% Biomass / 40% Polyphosphate",
    file: "ijn1463_fluxer_biomass60_polyp40_subsystems.json",
  },
  {
    id: "polyphosphate",
    label: "Polyphosphate maximization",
    file: "ijn1463_fluxer_polyp_subsystems.json",
  },
];
const DEFAULT_SCENARIO = SCENARIOS[0].id;

function humanizeSubsystem(raw) {
  return raw
    .replace(/^S_/, "")
    .replace(/_+/g, " ")
    .trim();
}

async function main() {
  const scenarioGraphs = await Promise.all(
    SCENARIOS.map(async (scenario) => {
      const raw = JSON.parse(await readFile(path.join(DATA_DIR, scenario.file), "utf-8"));
      return { ...scenario, nodes: raw.graph.nodes, links: raw.graph.links };
    }),
  );

  const reactionSubsystems = new Set();
  for (const { nodes } of scenarioGraphs) {
    for (const n of nodes) if (n.class === "reaction") reactionSubsystems.add(n.subsystem);
  }
  const subsystemIndexByName = new Map(
    [...reactionSubsystems].sort().map((name, index) => [name, index]),
  );

  // --- Flux -> edge width: log-scaled (values span several orders of
  // magnitude, so a linear map would make almost every edge invisible),
  // over every scenario's flux values combined so the scale itself never
  // shifts when switching scenarios. ---
  const allFluxes = scenarioGraphs.flatMap(({ links }) =>
    links.map((l) => Math.abs(l.flux)).filter((f) => f > 0),
  );
  const logMin = Math.log(Math.min(...allFluxes));
  const logMax = Math.log(Math.max(...allFluxes));
  const logSpan = logMax - logMin || 1;
  function fluxNormOf(flux) {
    const abs = Math.abs(flux);
    if (abs <= 0) return 0;
    return Math.max(0, Math.min(1, (Math.log(abs) - logMin) / logSpan));
  }

  // --- Union nodes: one entry per id across every scenario ---
  const nodeMap = new Map();
  for (const { id: scenarioId, nodes } of scenarioGraphs) {
    for (const n of nodes) {
      let entry = nodeMap.get(n.id);
      if (!entry) {
        entry =
          n.class === "reaction"
            ? {
                id: n.id,
                label: n.id,
                kind: "reaction",
                name: n.name || n.id,
                subsystem: humanizeSubsystem(n.subsystem),
                subsystemIndex: subsystemIndexByName.get(n.subsystem) ?? -1,
                scenarios: {},
              }
            : {
                id: n.id,
                label: n.id,
                kind: "metabolite",
                name: n.name || n.id,
                localization: n.localization || null,
                scenarios: {},
              };
        nodeMap.set(n.id, entry);
      }
      entry.scenarios[scenarioId] = entry.kind === "reaction" ? { flux: n.flux, active: 1 } : { active: 1 };
    }
  }
  // A node absent from a scenario (filtered out upstream as zero-flux or
  // orphaned) is still part of the union graph, at its usual position —
  // it's just inactive there.
  for (const entry of nodeMap.values()) {
    for (const { id: scenarioId } of scenarioGraphs) {
      if (!entry.scenarios[scenarioId]) {
        entry.scenarios[scenarioId] = entry.kind === "reaction" ? { flux: null, active: 0 } : { active: 0 };
      }
    }
  }

  // --- Union edges: keyed by source->target (each scenario file has no
  // parallel edges between the same pair, verified against the source
  // data, so this key is safe as a stable id). ---
  const edgeMap = new Map();
  for (const { id: scenarioId, links } of scenarioGraphs) {
    for (const l of links) {
      const key = `${l.source}->${l.target}`;
      let entry = edgeMap.get(key);
      if (!entry) {
        entry = { id: key, source: l.source, target: l.target, scenarios: {} };
        edgeMap.set(key, entry);
      }
      entry.scenarios[scenarioId] = { flux: l.flux, fluxNorm: fluxNormOf(l.flux), active: 1 };
    }
  }
  for (const entry of edgeMap.values()) {
    for (const { id: scenarioId } of scenarioGraphs) {
      if (!entry.scenarios[scenarioId]) {
        entry.scenarios[scenarioId] = { flux: null, fluxNorm: 0, active: 0 };
      }
    }
  }

  // Seed top-level flux/fluxNorm/active from the default scenario — these
  // are the fields the component's Cytoscape style mappers read on first
  // paint; `scenarios` stays alongside for the component to switch off of.
  const outNodes = [...nodeMap.values()].map((n) => ({
    data: { ...n, ...n.scenarios[DEFAULT_SCENARIO] },
  }));
  const outEdges = [...edgeMap.values()].map((e) => ({
    data: { ...e, ...e.scenarios[DEFAULT_SCENARIO] },
  }));

  const output = {
    meta: {
      generatedAt: new Date().toISOString(),
      nodeCount: outNodes.length,
      edgeCount: outEdges.length,
      subsystemCount: subsystemIndexByName.size,
    },
    scenarios: scenarioGraphs.map(({ id, label, file, nodes, links }) => ({
      id,
      label,
      sourceFile: file,
      nodeCount: nodes.length,
      edgeCount: links.length,
    })),
    defaultScenario: DEFAULT_SCENARIO,
    elements: { nodes: outNodes, edges: outEdges },
  };

  await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, JSON.stringify(output));

  console.log(
    `[generate-metabolic-network] ${outNodes.length} nodes, ${outEdges.length} edges, ` +
      `${output.meta.subsystemCount} subsystems, ${output.scenarios.length} scenarios -> ` +
      path.relative(ROOT, OUTPUT_PATH),
  );
}

main().catch((err) => {
  console.error("[generate-metabolic-network] failed:", err);
  process.exitCode = 1;
});
